def _is_crossdomain(parsed: dict) -> bool:
    """
    检测是否跨领域求职场景。
    判断依据：jd_analysis.match_score 中包含跨领域特征词或百分比≤55%。
    同时检查 bullets 的 match_reason：如果全部是"可迁移"类型且没有"直接匹配"→跨领域。
    """
    jda = parsed.get("jd_analysis", {})
    ms_text = jda.get("match_score", "")

    # 信号1：jd_analysis 中明确标注了跨领域/可迁移
    cross_signals = ["可迁移", "跨领域", "领域不同", "非直接匹配", "转型"]
    if any(s in ms_text for s in cross_signals):
        return True

    # 信号2：百分比≤55%（跨领域场景上限）
    pct_match = re.search(r'(\d+)%', ms_text)
    if pct_match and int(pct_match.group(1)) <= 45:
        return True

    # 信号3：所有 bullets 的 match_reason 都是"可迁移"开头，没有"直接匹配"
    all_bullets = []
    for exp in parsed.get("experience", []):
        all_bullets.extend(exp.get("bullets", []))
    if all_bullets:
        reasons = [b.get("match_reason", "") if isinstance(b, dict) else "" for b in all_bullets]
        reasons = [r for r in reasons if r.strip()]
        if reasons and all(r.startswith("可迁移") for r in reasons):
            return True

    return False


def _strip_match_reason(parsed: dict) -> None:
    """将所有 experience bullets 的 match_reason 置为空字符串"""
    for exp in parsed.get("experience", []):
        for b in exp.get("bullets", []):
            if isinstance(b, dict):
                b["match_reason"] = ""


def _normalize_jd_analysis(raw: dict) -> dict:
    """
    归一化 JD 分析结果，确保 match_score 存在、gaps 每条都是 {gap, suggestion} 对象。
    AI 模型不一定严格遵循格式，这里做兜底处理。
    """
    analysis = dict(raw) if raw else {}

    # match_score 兜底：如果 AI 没返回，给空字符串（前端判断显示）
    if "match_score" not in analysis:
        analysis["match_score"] = ""

    # gaps 归一化：字符串 → {gap, suggestion} 对象
    raw_gaps = analysis.get("gaps", [])
    normalized_gaps = []
    for item in raw_gaps:
        if isinstance(item, str):
            normalized_gaps.append({"gap": item, "suggestion": ""})
        elif isinstance(item, dict):
            normalized_gaps.append({
                "gap": item.get("gap", ""),
                "suggestion": item.get("suggestion", ""),
            })
    analysis["gaps"] = normalized_gaps

    return analysis


def _strip_ability_tails(text: str) -> str:
    """
    从文本中移除「这证明了/这展示了/这培养了」等解释性后缀。
    DeepSeek 模型有强烈的中文简历写作先验，即使 prompt 明确禁止仍会生成这类句式。
    后处理是结构性的最后防线——无论模型输出什么，物理切除这些尾句。
    """
    if not text:
        return text

    # 句末/句中：，这XX了我（具备）...（的能力/的素养/的习惯）
    text = re.sub(
        r'[，。；]\s*这(?:证明|展示|体现|培养|锻炼|说明|反映|凸显)了我(?:具备|的)?[^，。；]*(?:的能力|的素养|的习惯|的潜力)?[。]?',
        '', text
    )
    # 句首：这证明了我...
    text = re.sub(
        r'^这(?:证明|展示|体现|培养|锻炼|说明|反映|凸显)了我(?:具备|的)?[^，。；]*(?:的能力|的素养|的习惯|的潜力)?[。]?\s*',
        '', text
    )
    # 清理残留：尾部逗号、双句号、连续标点
    text = text.rstrip('，, ； ')
    text = re.sub(r'。。+', '。', text)
    text = re.sub(r'[，,]\s*[。]', '。', text)  # "，。" → "。"
    return text.strip()


def _clean_core_strengths(raw_items: list) -> list:
    """对每条 core_strengths 执行尾句清洗。"""
    return [_strip_ability_tails(item) for item in raw_items if item]


def _clean_interview_tips(raw_tips: list) -> list:
    """对每条 interview_tip 的 answer_hint 执行尾句清洗。"""
    for tip in raw_tips:
        if not isinstance(tip, dict):
            continue
        questions = tip.get("questions", [])
        for q in questions:
            if isinstance(q, dict) and "answer_hint" in q:
                q["answer_hint"] = _strip_ability_tails(q["answer_hint"])
    return raw_tips


