def _parse_ai_response(ai_content: str) -> dict:
    """从 AI 返回的文本中提取 JSON，容错处理"""
    text = ai_content.strip()

    if "```json" in text:
        start = text.index("```json") + 7
        end = text.index("```", start)
        text = text[start:end].strip()
    elif "```" in text:
        start = text.index("```") + 3
        end = text.index("```", start)
        text = text[start:end].strip()

    return json.loads(text)


def _normalize_bullets(raw_bullets: list) -> list[BulletPoint]:
    """
    兼容处理：AI 可能返回纯字符串数组或对象数组。
    统一转为 BulletPoint 对象列表。
    """
    result = []
    for b in raw_bullets:
        if isinstance(b, str):
            result.append(BulletPoint(text=b, match_reason="", match_score="medium"))
        elif isinstance(b, dict):
            result.append(BulletPoint(
                text=b.get("text", ""),
                match_reason=b.get("match_reason", ""),
                match_score=b.get("match_score", "medium")
            ))
    return result


def _normalize_skills(raw_skills) -> list[SkillGroup]:
    """
    兼容处理：AI 可能返回分类对象数组或旧的纯字符串数组。
    统一转为 SkillGroup 对象列表。
    """
    if not raw_skills:
        return []

    # 如果第一个元素是 dict（新格式），直接解析
    if isinstance(raw_skills[0], dict):
        groups = []
        for s in raw_skills:
            groups.append(SkillGroup(
                category=s.get("category", "其他"),
                items=s.get("items", [])
            ))
        return groups

    # 如果第一个元素是 str（旧格式），全部塞到"专业技能"分组
    if isinstance(raw_skills[0], str):
        return [SkillGroup(category="专业技能", items=raw_skills)]

    return []


