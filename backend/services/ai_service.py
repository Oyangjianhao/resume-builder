def _generate_learning_guide(data: ResumeRequest) -> ResumeResponse:
    """
    当用户输入实质性为空时，生成学习与面试准备指导而非伪造简历。
    使用独立的 prompt 和 system message，绕过正常的简历生成流程。
    """
    target = data.target_position.strip()
    prompt = _build_learning_guide_prompt(data)

    system_msg = """你是一位经验丰富的职业规划顾问，专门帮助应届生制定学习和求职准备计划。

你的任务是为用户分析目标岗位的需求，并给出具体、可执行的学习指导。

核心原则：
1. 具体性：每条建议必须针对该岗位的真实需求，杜绝"多练习""多学习"等空洞表述
2. 可执行性：学习路线要说清楚先做什么后做什么，每阶段大概需要多长时间
3. 真实性：面试问题要反映该岗位的真实面试风格，不要编造
4. 实用性：建议的项目要能真正帮助用户积累相关经验，而不是为了凑数
5. 不编造：绝对不要编造用户没有的经历、数据或成就"""

    response = requests.post(
        DEEPSEEK_API_URL,
        headers={
            "Content-Type": "application/json",
            "Authorization": f"Bearer {DEEPSEEK_API_KEY}"
        },
        json={
            "model": DEEPSEEK_MODEL,
            "messages": [
                {"role": "system", "content": system_msg},
                {"role": "user", "content": prompt}
            ],
            "temperature": 0.3,
            "max_tokens": 6000
        },
        timeout=120
    )
    response.raise_for_status()
    result = response.json()

    ai_content = result["choices"][0]["message"]["content"]
    usage = result.get("usage", {})
    parsed = _parse_ai_response(ai_content)

    # 解析技能（学习指南中的推荐技能列表）
    skills = _normalize_skills(parsed.get("skills", []))

    # 解析面试话术
    interview_tips = _normalize_interview_tips(parsed.get("interview_tips", []))

    return ResumeResponse(
        name=data.personal.name,
        phone=data.personal.phone,
        email=data.personal.email,
        target_position=target,
        job_objective=parsed.get("job_objective", ""),
        career_summary=parsed.get("career_summary", ""),
        core_strengths=parsed.get("core_strengths", []),
        self_evaluation=parsed.get("self_evaluation", ""),
        interview_tips=interview_tips,
        education=data.education,
        experience=[],           # 无经历 = 空数组，前端据此判断为学习指导模式
        project_experience=[],   # 同上
        skills=skills,
        certificates=parsed.get("certificates", []),
        jd_analysis=_normalize_jd_analysis(parsed.get("jd_analysis", {})),
        token_usage={
            "input_tokens": usage.get("prompt_tokens", 0),
            "output_tokens": usage.get("completion_tokens", 0),
            "total_tokens": usage.get("total_tokens", 0),
        },
        summary=parsed.get("summary", parsed.get("career_summary", "")),
    )


def generate_resume(data: ResumeRequest) -> ResumeResponse:
    """主入口：接收用户数据 → 调 AI → 返回结构化简历内容"""
    # 空输入检测：如果所有内容板块实质性为空，生成学习指导而非伪造简历
    if _is_essentially_empty(data) and data.target_position.strip():
        return _generate_learning_guide(data)

    has_jd = bool(data.job_description.strip())
    has_exp = len(data.experience) > 0 or len(data.project_experience) > 0
    prompt = _build_prompt(data)
    result = _call_deepseek(prompt, has_jd=has_jd, has_exp=has_exp)

    ai_content = result["choices"][0]["message"]["content"]
    usage = result.get("usage", {})
    parsed = _parse_ai_response(ai_content)

    # 跨领域检测：如果 AI 判定为跨领域场景，强制清空所有 match_reason
    if has_jd and _is_crossdomain(parsed):
        _strip_match_reason(parsed)

    # Safety net：无经历材料时，硬截断 core_strengths 至最多3条，防止 AI 编造第4条
    if not has_exp:
        parsed["core_strengths"] = parsed.get("core_strengths", [])[:3]

    # 按类型拆分经历
    all_exp = parsed.get("experience", [])
    work_exp = []
    project_exp = []
    for exp in all_exp:
        exp_type = exp.get("type", "")
        if not exp_type:
            exp_type = "work" if exp.get("company") else "project"
            exp["type"] = exp_type

        # 兼容处理 bullets（新格式: 对象数组 / 旧格式: 字符串数组）
        exp["bullets"] = _normalize_bullets(exp.get("bullets", []))
        # 清洗 bullets 文本中的解释性后缀（这证明了/这培养了 等）
        for bp in exp["bullets"]:
            bp.text = _strip_ability_tails(bp.text)

        if exp_type == "work":
            work_exp.append(PolishedExperience(**exp))
        else:
            project_exp.append(PolishedExperience(**exp))

    # 解析技能（新格式: SkillGroup[] / 旧格式: str[]）
    skills = _normalize_skills(parsed.get("skills", []))

    # 解析面试话术
    interview_tips = _clean_interview_tips(
        _normalize_interview_tips(parsed.get("interview_tips", []))
    )

    return ResumeResponse(
        name=data.personal.name,
        phone=data.personal.phone,
        email=data.personal.email,
        target_position=data.target_position,
        # v0.2 新板块
        job_objective=parsed.get("job_objective", ""),
        career_summary=parsed.get("career_summary", ""),
        core_strengths=(
            _clean_core_strengths(parsed.get("core_strengths", []))
            if not has_exp else
            ensure_core_strengths_count(
                _clean_core_strengths(parsed.get("core_strengths", [])), has_jd,
                data.job_description if has_jd else "", data.target_position
            )
        ),
        self_evaluation=parsed.get("self_evaluation", ""),
        interview_tips=interview_tips,
        # 经历
        education=data.education,
        experience=work_exp,
        project_experience=project_exp,
        # 技能 & 证书
        skills=skills,
        certificates=parsed.get("certificates", []),
        # 分析 & 元数据
        jd_analysis=_normalize_jd_analysis(parsed.get("jd_analysis", {})),
        token_usage={
            "input_tokens": usage.get("prompt_tokens", 0),
            "output_tokens": usage.get("completion_tokens", 0),
            "total_tokens": usage.get("total_tokens", 0),
        },
        # 向后兼容
        summary=parsed.get("summary", parsed.get("career_summary", "")),
    )
